def validate(d):
    for p in d['points']:
        s=p.get('spec',{})
        for key in ['quantity','quantityStatus','height','heightStatus','location','basis','measurement']:
            if not isinstance(s.get(key),str) or not s[key].strip(): raise ValueError(f'{p["id"]}: missing spec.{key}')
        if s['location']!=p['placement']: raise ValueError(f'{p["id"]}: stale installation location')
        if len(s.get('perMarker',[]))!=len(p['anchors']): raise ValueError(f'{p["id"]}: marker count/spec mismatch')
        if not all(s['perMarker']): raise ValueError(f'{p["id"]}: empty marker count')

